func (id *Identity) AllowsDelegatedMethod(service, method string) bool {
	if id.Delegation == nil {
		return true
	}
	required, ok := DelegationMethodScopes[service+"."+method]
	if !ok {
		return false
	}
	for _, scope := range id.Delegation.Scopes {
		if scope == "longhouse.full" || scope == required {
			return true
		}
	}
	// Every approved grant can inspect the identity it represents.
	return service == "auth" && method == "Me" && len(id.Delegation.Scopes) > 0
}
